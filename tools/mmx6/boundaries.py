"""boundaries.py [--out FILE] [--self-test] [--psyq-dir DIR] -- forced function/object boundaries per program (T8.c1).

Programs: SLUS_013.95 (text 0x80010000..0x8008F000, exeproof.load_image) + every `code` row of config/loadmap.txt
(rock/NN.bin at its base, sha1 = manifest, via loadmap.load_members). Ghidra side: config/ghidra/<prog>.jsonl.
Rows (addresses "0x%08x", spans [lo, hi) with hi exclusive):
  jtbl <table_lo> <table_hi> <func> <src> [note]
    scan: every `jr X` (X != ra) in the program's code range whose X comes from `lw X,off(B)`, B from `addu B,P,Q`
    with exactly one of P/Q a lui(+addiu/ori) constant C and the other `sll I,J,2`; table = C + off (covers both gcc
    forms: lui/addiu/addu/lw 0 and lui at/addu at/lw %lo(at)). Extent: `sltiu _,J,N` (J not redefined before the
    sll) -> N words, else consecutive words pointing into the program's code range. The table must lie in the
    image and not contain the dispatch. Defs are looked up backwards within WINDOW instructions.
    ghidra: `switchdataD_*` labels, entry count from the "Address table[N] created" bookmark at the same address.
    src both|scan|ghidra; func = the Ghidra func start at or before the jr (`-` if none; ghidra-only: the label's
    reference is unknown, `-`). Disagreements carry a reason computed below (reasons_scan / reasons_ghidra); a hi
    mismatch on a `both` row is noted `ghidra_hi=0x..`. A one-sided row with no reason -> rc 1.
  lib <lo> <hi> <LIB/OBJ>: a Ghidra func (name or a single-candidate "Possible X.OBJ/name" plate) whose name is a
    label of a PsyQ signature object (<psyq-dir>/<ver>/*.json, ver from the export's `psyqNNN` archive) and whose
    signature (?? = wildcard) matches the image at lo = func - label offset; hi = lo + sig length. Emitted only
    when exactly one (lib, obj, lo) verifies; ambiguous ones are counted in the header.
  optcand <lo> <hi> <reason> funcs=<n>: contiguous Ghidra funcs (bodies = [start, next func/data start)) whose
    first PROLOGUE instructions set fp from sp (`addu/or fp,sp,zero`): reason fp-frame+arg-spill when a0..a3 are
    also stored to fp-relative slots there, else fp-frame (-O0 shapes); a span's reason = its funcs' reasons joined.
  fstart <addr> calls=<n>: in-program `jal` targets, jal inside a Ghidra func body, target not a Ghidra func start;
    exe rows add ovl_calls=<n> (such jals from overlay func bodies into the exe text).
rc 0 ok; 1 unexplained disagreement or self-test failure; 2 bad inputs. --self-test runs the scan on synthetic
bytes (no game data). Stdlib only.
"""
