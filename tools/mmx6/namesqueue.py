#!/usr/bin/env python3
"""namesqueue.py -- name-candidate queue over every lead table (2.2 T11).

  build        read docs/leads/*.tsv + config/oracle.strnames.tsv + config/oracle.proto-*.functions.tsv,
               write config/names-queue.tsv (keys, addresses, our own snake_case words only) and the refused
               leads to build/names-refused.tsv (prog vram candidate source evidence-key reason)
  check [--source S]
               read config/names-queue.tsv + config/names-verdicts.tsv (hand-edited); key = (prog, vram,
               candidate, source, evidence-key); prints NAMESQUEUE judged <j> of <n> (n = queue rows, of source S
               when given); a verdict whose key is not in the queue, a verdict word outside admitted|held|rejected,
               or a repeated key is a NAMESQUEUE REFUSE line; rc 0 iff j = n and no refusal
  --self-test  planted fixtures in build/ (removed after); prints NAMESQUEUE CONTROL OK (check must catch a
               planted unjudged row and a planted verdict for a row not in the queue)

Columns: prog vram candidate source evidence-key basis-kind tier overlay-ref.
Validity sets come from tracked files only (git ls-files): function starts = oracle functions (unit, vram)
+ `type:func` / `func_` symbols + Ghidra `func` records (config/ghidra/<prog>.jsonl, inside a ram/RAM/CODE block);
data symbols = other symbols + Ghidra `data`/`label` records + D_<8hex> tokens in src/<prog>/, src/shared/,
include/. Prog `ovl_<base>` = the one member of that load group (Ghidra image_base) holding the vram.
overlay-ref `ovl` = an exe vram named in src/rock_*/ or src/shared/rock_*/. A row is refused (counted, never rewritten) when its vram is not in its prog's sets, its candidate
fails style, a community basis carries a tier above `lead`, or (prog, vram, source) repeats.
"""
import collections
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = "config/names-queue.tsv"
REFUSED = "build/names-refused.tsv"
VERDICTS = "config/names-verdicts.tsv"
VERDICT_WORDS = ("admitted", "held", "rejected")
EXE = "SLUS_013.95"
LEADS = ["tweaks-index", "ram", "objects", "assets", "strings", "proto", "x5", "community"]
HEADER = "# prog\tvram\tcandidate\tsource\tevidence-key\tbasis-kind\ttier\toverlay-ref"
GENLINE = "# %s -- generated by tools/mmx6/namesqueue.py build; do not edit (keys, addresses, our own words only)" % OUT
TIERS = ("lead", "consistent-with-bytes", "proven-at-gate")
BASES = ("string", "xref", "oracle", "debug", "community", "x4", "sdk")
STYLE = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")
ADDR = re.compile(r"0x[0-9A-Fa-f]{8}(?![0-9A-Fa-f])")
ONE = re.compile(r"^0x[0-9A-Fa-f]{8}$")
PV = re.compile(r"([A-Za-z0-9_.]+):(0x[0-9A-Fa-f]{8})")
DTOK = re.compile(r"\bD_([0-9A-F]{8})\b")
FDEF = re.compile(r"INCLUDE_ASM\([^)]*\bfunc_([0-9A-F]{8})\s*\)|^[A-Za-z_][\w \t\*]*\bfunc_([0-9A-F]{8})\s*\([^;\n]*$",
                  re.M)
SYM = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$")


def snake(text):
    t = re.sub(r"\([^)]*\)", " ", text).split(",")[0].lower()
    t = re.sub(r"[^a-z0-9]+", "_", t).strip("_")
    return "_".join(t.split("_")[:5]) if t else ""


def hexv(v):
    return "0x%08X" % int(v, 16)


def list_files(root, sub, tracked):
    if tracked:
        r = subprocess.run(["git", "-C", root, "ls-files", "-z", "--", sub], capture_output=True, check=True)
        return sorted(p for p in r.stdout.decode().split("\0") if p)
    out = []
    for d, _, fs in os.walk(os.path.join(root, sub)):
        out += [os.path.relpath(os.path.join(d, f), root) for f in fs]
    return sorted(out)


def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as f:
        return f.read()


def table(root, rel):
    """Yield (line_no, dict) per data row; header = first line whose fields name the columns."""
    cols = None
    for n, line in enumerate(read(root, rel).split("\n"), 1):
        if not line.strip():
            continue
        if cols is None:
            h = line[2:] if line.startswith("# ") else line
            if "\t" in h:
                cols = h.split("\t")
            continue
        if line.startswith("#"):
            continue
        f = line.split("\t")
        yield n, dict(zip(cols, f + [""] * (len(cols) - len(f))))


def sets(root, tracked):
    funcs, data = collections.defaultdict(set), collections.defaultdict(set)
    progs = set()
    for rel in list_files(root, "config", tracked):
        m = re.match(r"config/oracle\.proto-.*\.functions\.tsv$", rel)
        if m:
            for _, r in table(root, rel):
                funcs[r["unit"]].add(int(r["vram"], 16))
        m = re.match(r"config/symbols\.(.+)\.txt$", rel)
        if m:
            prog = m.group(1)
            progs.add(prog)
            for line in read(root, rel).split("\n"):
                s = SYM.match(line)
                if not s:
                    continue
                v = int(s.group(2), 16)
                if "type:func" in s.group(3) or s.group(1).startswith("func_"):
                    funcs[prog].add(v)
                else:
                    data[prog].add(v)
    groups = collections.defaultdict(set)
    for rel in list_files(root, "config/ghidra", tracked):
        if not rel.endswith(".jsonl"):
            continue
        recs = [json.loads(line) for line in read(root, rel).split("\n") if line.strip()]
        prog = recs[0]["name"]
        progs.add(prog)
        groups[int(recs[0]["image_base"], 16)].add(prog)
        ram = [(int(r["start"], 16), int(r["end"], 16)) for r in recs if r["k"] == "block" and r["name"].lower() in ("ram", "code")]
        for r in recs:
            if r["k"] in ("func", "data", "label") and "addr" in r:
                v = int(r["addr"], 16)
                if any(lo <= v <= hi for lo, hi in ram):
                    (funcs if r["k"] == "func" else data)[prog].add(v)
    progs |= set(funcs)
    ovl_tokens = set()
    for rel in list_files(root, "src", tracked) + list_files(root, "include", tracked):
        parts = rel.split("/")
        if parts[0] == "src" and len(parts) > 2 and parts[1] == "shared":
            prog = parts[2] if parts[2] in progs else EXE
        elif parts[0] == "src" and len(parts) > 2:
            prog = parts[1]
        else:
            prog = EXE
        text = read(root, rel)
        data[prog].update(int(h, 16) for h in DTOK.findall(text))
        # T11: a func_ defined in this prog's src (INCLUDE_ASM or a C definition) is a start
        funcs[prog].update(int(a or b, 16) for a, b in FDEF.findall(text))
        if parts[0] == "src" and len(parts) > 2 and (parts[1].startswith("rock_") or
                                                     (parts[1] == "shared" and parts[2].startswith("rock_"))):
            ovl_tokens.update(re.findall(r"\b(?:func|D)_([0-9A-F]{8})\b", text))
    return funcs, data, sorted(progs | set(data)), ovl_tokens, groups


class Q:
    def __init__(self, funcs, data, progs, ovl, groups):
        self.funcs, self.data, self.progs, self.ovl, self.groups = funcs, data, progs, ovl, groups
        self.rows, self.seen = [], set()
        self.refused = collections.Counter()
        self.refused_rows = []

    def holds(self, prog, v):
        return v in self.funcs.get(prog, ()) or v in self.data.get(prog, ())

    def resolve(self, v, exe_only=False):
        """Prog whose sets hold v (exe first); (prog, None) or (None, reason)."""
        if self.holds(EXE, v):
            return EXE, None
        if exe_only:
            return None, "not-symbol"
        hits = [p for p in self.progs if p != EXE and self.holds(p, v)]
        if len(hits) == 1:
            return hits[0], None
        return None, ("ambiguous-prog" if hits else "not-symbol")

    def placeholder(self, prog, v):
        return ("func_%08X" if v in self.funcs.get(prog, ()) else "D_%08X") % v

    def add(self, prog, vram, cand, source, key, basis, tier, reason=None):
        """Validate one row; refuse (counted) or keep. cand None = placeholder."""
        v = int(vram, 16) if isinstance(vram, str) else vram
        if reason is None and re.fullmatch(r"ovl_[0-9A-Fa-f]{8}", prog or ""):
            hits = sorted(p for p in self.groups.get(int(prog[4:], 16), ()) if self.holds(p, v))
            if len(hits) == 1:
                prog = hits[0]
            else:
                reason = "ambiguous-prog" if hits else "not-symbol"
        if reason is None:
            if prog not in self.progs:
                reason = "unknown-prog"
            elif not self.holds(prog, v):
                reason = "not-symbol"
            else:
                isf = v in self.funcs.get(prog, ())
                if cand is None:
                    cand = self.placeholder(prog, v)
                ph = re.fullmatch(r"(func|D)_([0-9A-F]{8})", cand)
                if ph:
                    ok = int(ph.group(2), 16) == v and (ph.group(1) == "func") == isf
                else:
                    ok = bool(STYLE.match(cand)) and len(cand) <= 40
                if not ok:
                    reason = "style"
                elif basis not in BASES or tier not in TIERS[:2]:
                    reason = "bad-basis-or-tier"
                elif (ph or basis == "community") and tier != "lead":
                    reason = "community-tier" if basis == "community" else "placeholder-tier"
                elif (prog, v, source) in self.seen:
                    reason = "duplicate"
        if reason:
            self.refused[reason] += 1
            self.refused_rows.append((prog or "-", v, cand or "-", source, key, reason))
            return reason
        self.seen.add((prog, v, source))
        ovl = "ovl" if prog == EXE and "%08X" % v in self.ovl else "-"
        self.rows.append((prog, v, cand, source, key, basis, tier, ovl))
        return None


def derive(root, q):
    L = lambda n: "docs/leads/%s.tsv" % n
    for n, r in table(root, L("tweaks-index")):
        k, loc = r["kind"], r["location"].strip()
        key = "tweaks-index.tsv:%d" % n
        if k in ("func", "var", "table", "buffer", "struct") and ONE.match(loc):
            v = int(loc, 16)
            q.add(EXE, v, snake(r["subject"]), "tweaks", key, "community", "lead",
                  None if q.holds(EXE, v) else "not-symbol")
        elif k in ("ovl-func", "ovl-table") and re.match(r"^ovl 0x[0-9A-Fa-f]{8}$", loc):
            v = int(loc[4:], 16)
            hits = [p for p in q.progs if q.holds(p, v)]
            prog = hits[0] if len(hits) == 1 else EXE
            q.add(prog, v, snake(r["subject"]), "tweaks", key, "community", "lead",
                  None if len(hits) == 1 else ("ambiguous-prog" if hits else "not-symbol"))
    for n, r in table(root, L("ram")):
        a = r["address"].strip()
        if r["kind"] in ("func", "var", "table", "struct", "buffer") and ONE.match(a):
            v = int(a, 16)
            prog, why = q.resolve(v)
            q.add(prog or EXE, v, snake(r["role"]), "ram-" + r["source"].lower(), r["key"], "community", "lead", why)
    objects = []
    for n, r in table(root, L("objects")):
        m = PV.fullmatch(r["prog_vram"].strip())
        if not m:
            continue
        objects.append((r["table"], r["type_id"], m.group(1), int(m.group(2), 16)))
        basis = "community" if r["name_source"].startswith("refs/leads/tweaks") else "xref"
        named = r["entity_name"] not in ("-", "")
        tier = "consistent-with-bytes" if named and basis == "xref" and r["tier"] == "proven" else "lead"
        cand = ("update_" if basis == "community" else "") + r["entity_name"] if named else None
        q.add(m.group(1), m.group(2), cand, "objects",
              "objects.tsv:%s:%s" % (r["table"], r["type_id"]), basis, tier)
    for n, r in table(root, L("assets")):
        key = "assets.tsv:" + r["asset_key"]
        m = PV.fullmatch(r["loader"].strip())
        if not m:
            continue
        q.add(m.group(1), m.group(2), None, "assets", key, "xref", "lead")
        t = re.match(r"D_([0-9A-F]{8})", r["table"].strip())
        if t:
            q.add(m.group(1), "0x" + t.group(1), None, "assets", key, "xref", "lead")
    for n, r in table(root, L("strings")):
        if r["build"] != "retail":
            continue
        for prog, vram in PV.findall(r["referencing-function"]):
            q.add(prog, vram, None, "strings", "sha1=" + r["sha1"], "string", "lead")
    for n, r in table(root, "config/oracle.strnames.tsv"):
        lib = re.match(r"lib:([^:]+):", r["name"])
        key = "strnames:" + r["key"] + (":lib=" + lib.group(1) if lib else "")
        q.add(r["unit"], r["vram"], None, "strnames", key, "string", "lead")
    for n, r in table(root, L("proto")):
        m = PV.fullmatch(r["retail"].strip())
        if not m or r["debug_hint"] in ("-", "no-callers", ""):
            continue
        q.add(m.group(1), m.group(2), None, "proto",
              "proto:%s:%s:%s" % (r["build"], r["build_address"], r["debug_hint"]), "debug", "lead")
    for n, r in table(root, L("x5")):
        for a in ADDR.findall(r["x6_address"]):
            v = int(a, 16)
            prog, why = q.resolve(v)
            q.add(prog or EXE, v, snake(r["x5_counterpart"]), "x5", "x5.tsv:%d" % n, "community", "lead", why)
    for n, r in table(root, L("community")):
        m = re.match(r"docs/leads/objects\.tsv (\S+) (0x[0-9A-Fa-f]+)", r["join"])
        if not m:
            continue
        for tb, tid, prog, v in objects:
            if tb == m.group(1) and tid == m.group(2):
                q.add(prog, v, "update_" + snake(r["term"]), "community", "community.tsv:%d" % n, "community", "lead")


def build(root, tracked=True, quiet=False):
    q = Q(*sets(root, tracked))
    derive(root, q)
    rows = sorted(q.rows, key=lambda r: (r[0], r[1], r[3]))
    text = GENLINE + "\n" + HEADER + "\n" + "".join(
        "\t".join([p, "0x%08X" % v] + list(rest)) + "\n" for p, v, *rest in rows)
    os.makedirs(os.path.join(root, "config"), exist_ok=True)
    with open(os.path.join(root, OUT), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    refused = sorted(q.refused_rows, key=lambda r: (r[0], r[1], r[3], r[4], r[2], r[5]))
    os.makedirs(os.path.join(root, "build"), exist_ok=True)
    with open(os.path.join(root, REFUSED), "w", encoding="utf-8", newline="\n") as f:
        f.write("# prog\tvram\tcandidate\tsource\tevidence-key\treason\n" + "".join(
            "\t".join([p, "0x%08X" % v] + list(rest)) + "\n" for p, v, *rest in refused))
    if not quiet:
        for name, c in (("source", collections.Counter(r[3] for r in rows)),
                        ("tier", collections.Counter(r[6] for r in rows)), ("refused", q.refused)):
            for k in sorted(c):
                print("NAMESQUEUE %s=%s n=%d" % (name, k, c[k]))
        print("NAMESQUEUE BUILD %d rows" % len(rows))
    return q, rows


def vkey(prog, vram, cand, source, key):
    """Queue/verdict join key; vram normalised to 0x%08X (None when not hex)."""
    try:
        return (prog, "0x%08X" % int(vram, 16), cand, source, key)
    except ValueError:
        return None


def check(root, source=None, quiet=False):
    """Judged count of the queue against the verdicts file; returns (j, n, refusal lines)."""
    queue = set()
    for line in read(root, OUT).splitlines():
        f = line.split("\t")
        if line.startswith("#") or len(f) < 5:
            continue
        queue.add(vkey(*f[:5]))
    want = {k for k in queue if source is None or k[3] == source}
    refuse, judged, seen = [], set(), set()
    text = read(root, VERDICTS) if os.path.exists(os.path.join(root, VERDICTS)) else ""
    for n, line in enumerate(text.splitlines(), 1):
        if line.startswith("#") or not line.strip():
            continue
        f = line.split("\t")
        k = vkey(*f[:5]) if len(f) >= 6 else None
        why = ("short-or-bad-row" if k is None else "duplicate-key" if k in seen
               else "not-in-queue" if k not in queue else "bad-verdict" if f[5] not in VERDICT_WORDS else None)
        if k is not None:
            seen.add(k)
        if why:
            refuse.append("NAMESQUEUE REFUSE %s:%d %s" % (VERDICTS, n, why))
        elif k in want:
            judged.add(k)
    if not quiet:
        for r in refuse:
            print(r)
        print("NAMESQUEUE judged %d of %d" % (len(judged), len(want)))
    return len(judged), len(want), refuse


