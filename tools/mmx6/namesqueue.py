def self_test():
    tmp = os.path.join(ROOT, "build", "namesqueue-selftest-%d" % os.getpid())
    try:
        for rel, body in FIX.items():
            os.makedirs(os.path.dirname(os.path.join(tmp, rel)), exist_ok=True)
            with open(os.path.join(tmp, rel), "w") as f:
                f.write(body)
        q, rows = build(tmp, tracked=False, quiet=True)
        got = {(r[0], r[1], r[3]): r for r in rows}
        R = q.refused
        assert R["not-symbol"] == 1, R            # tweaks 0x80099999
        assert R["style"] == 1, R                 # tweaks 9lives
        assert R["ambiguous-prog"] == 1, R        # ovl 0x800EA1D8 in rock_02 and rock_03
        assert R["duplicate"] == 1, R             # ram 0x80070000 twice
        assert got[("rock_02", 0x800EA300, "tweaks")][2] == "stage_objects", got
        assert got[(EXE, 0x80070000, "ram-kuumba123")][4] == "k:1", got
        o = got[(EXE, 0x80020000, "objects")]
        assert o[2] == "boss_a" and o[6] == "consistent-with-bytes" and o[7] == "ovl", o
        assert got[("rock_02", 0x800EA300, "objects")][2] == "enemy_slot_alloc", got   # ovl_ group resolved
        assert got[(EXE, 0x80070000, "ram-kuumba123")][7] == "-", got   # src/shared/SLUS_013.95 token only
        assert got[(EXE, 0x80020000, "community")][2:7:4] == ("update_boss_a", "lead"), got
        assert got[(EXE, 0x80020000, "strnames")][2:5] == ("func_80020000", "strnames", "strnames:abc:lib=LIBX")
        assert q.add(EXE, 0x80070000, "game_state", "planted", "k", "community", "consistent-with-bytes") == "community-tier"
        assert q.add(EXE, 0x8002D2B0, "func_80000000", "planted", "k", "xref", "lead") == "style"
        assert q.add(EXE, 0x80030000, None, "planted", "k", "xref", "lead") is None   # Ghidra func only
        assert q.rows[-1][2] == "func_80030000", q.rows[-1]
        assert q.add(EXE, 0x80040000, None, "planted", "k", "xref", "lead") is None   # Ghidra label
        assert q.add(EXE, 0x20000000, None, "planted", "k", "xref", "lead") == "not-symbol"   # outside ram
        assert q.add("ovl_800E9860", 0x800EA1D8, None, "planted", "k", "xref", "lead") == "ambiguous-prog"
        assert q.add(EXE, 0x8002D2B0, "move_object", "planted", "k", "x4", "consistent-with-bytes") is None
        assert q.add(EXE, 0x8002D2B0, "move_object", "planted", "k", "x4", "consistent-with-bytes") == "duplicate"
        b1 = read(tmp, OUT)
        q2, _ = build(tmp, tracked=False, quiet=True)
        assert read(tmp, OUT) == b1 and b1.endswith("\n") and b1.split("\n")[1] == HEADER
        ref = read(tmp, REFUSED).splitlines()
        assert len(ref) == 1 + sum(q2.refused.values()), ref
        assert "SLUS_013.95\t0x80099999\tmissing_thing\ttweaks\ttweaks-index.tsv:2\tnot-symbol" in ref, ref
        qrows = [l.split("\t") for l in b1.splitlines() if not l.startswith("#")]
        vfile = os.path.join(tmp, VERDICTS)
        def judge(rows):
            with open(vfile, "w") as f:
                f.write("# fixture\n" + "".join("\t".join(r[:5] + [w, "-", "-"]) + "\n" for r, w in rows))
            return check(tmp, quiet=True)
        allv = [(r, "admitted") for r in qrows]
        assert judge(allv) == (len(qrows), len(qrows), []), "all judged"
        j, n, rf = judge(allv[1:])                                   # planted unjudged row
        assert j == n - 1 and rf == [], (j, n, rf)
        orphan = (["SLUS_013.95", "0x80099999", "x", "planted", "k"], "held")
        j, n, rf = judge(allv + [orphan])                            # planted verdict for a row not in the queue
        assert j == n and rf == ["NAMESQUEUE REFUSE %s:%d not-in-queue" % (VERDICTS, len(allv) + 2)], rf
        j, n, rf = judge(allv + [(qrows[0], "admitted")])           # duplicate key
        assert rf == ["NAMESQUEUE REFUSE %s:%d duplicate-key" % (VERDICTS, len(allv) + 2)], rf
        j, n, rf = judge([(qrows[0], "maybe")] + allv[1:])          # bad verdict word
        assert j == n - 1 and rf == ["NAMESQUEUE REFUSE %s:2 bad-verdict" % VERDICTS], rf
        src = qrows[0][3]
        assert check(tmp, source=src, quiet=True)[1] == sum(r[3] == src for r in qrows)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("NAMESQUEUE CONTROL OK")
    return 0


