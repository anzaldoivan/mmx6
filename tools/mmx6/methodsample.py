#!/usr/bin/env python3
"""Methods sample for gen 3 (3.0 T12): a frozen, stratified pick of ~60 residue functions.

Host tool. `--build` writes config/methods-sample.tsv from the committed inputs
campaign/ledger.tsv, campaign/refusecause.tsv, campaign/priorart.tsv (each must equal HEAD).
`--check` rebuilds from the blob ids recorded in the file's header and compares byte for byte
(rc 0, `METHODS-SAMPLE OK <n> rows`). Rules: docs/ops/methods-gen3.md `## Methods sample (3.0 T12)`.
"""
import subprocess, sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = "config/methods-sample.tsv"
INPUTS = ("campaign/ledger.tsv", "campaign/refusecause.tsv", "campaign/priorart.tsv")
# stratum -> quota (fixed; file order)
QUOTAS = (("declaration", 12), ("path", 9), ("reloc", 9), ("address", 6), ("rodata", 1),
          ("norow", 3), ("plateau", 10), ("jtbl-uncarved", 10))
PROGS = ("SLUS_013.95", "rock")
COLS = "stratum prog vram func blocker code closeness pins x5 x4 proto pc any split"


def git(*a):
    return subprocess.run(["git", "-C", str(ROOT), *a], check=True, capture_output=True,
                          text=True).stdout


def rows(text):
    return [l.split("\t") for l in text.splitlines() if l and not l.startswith("#")]


def stratum(blocker, cause):
    if cause:
        return cause
    if blocker.startswith("plateau:"):
        return "plateau"
    if blocker == "jtbl-uncarved":
        return "jtbl-uncarved"
    return None  # vendor, member-of, undrawn, routed, other plumbing: outside the sample


def close_key(c):
    if "/" not in c:
        return (Fraction(-1), 0)  # nocompile ranks below 0/n
    m, n = c.split("/")
    return (Fraction(int(m), int(n)), int(n))


def build(texts, blobs):
    ledger, cause, prior = (rows(t) for t in texts)
    causes = {(r[0], r[1]): (r[4], r[5]) for r in cause}
    pa = {(r[0], r[1]): r[4:8] for r in prior}
    seen_dup, cells = set(), {}
    for r in sorted(ledger, key=lambda r: (r[0].encode(), int(r[1], 16))):
        prog, vram, func, klass, closeness, _draft, blocker, pins = r[:8]
        if blocker == "vendor":
            continue
        if klass.startswith("dup:"):  # one member per dup cluster: the first by (prog, vram)
            if klass in seen_dup:
                continue
            seen_dup.add(klass)
        code, c = causes.get((prog, vram), ("-", None))
        s = stratum(blocker, c)
        if s is None:
            continue
        x5, x4, proto, pc = pa[(prog, vram)]
        x5, x4 = x5.split(":")[0], x4.split(":")[0]
        anyp = "1" if (x5 == "c" or x4 == "c" or proto != "-" or pc != "-") else "0"
        p = "SLUS_013.95" if prog == "SLUS_013.95" else "rock"
        cells.setdefault((s, p), []).append(
            [s, prog, vram, func, blocker, code, closeness, pins, x5, x4, proto, pc, anyp])
    out = []
    for s, q in QUOTAS:
        sizes = [len(cells.get((s, p), [])) for p in PROGS]
        tot = sum(sizes)
        if tot < q:
            sys.exit(f"methodsample: stratum {s} has {tot} rows < quota {q}")
        # largest remainder, ties to SLUS; at least 1 per program that has rows
        exact = [Fraction(q * n, tot) for n in sizes]
        k = [int(e) for e in exact]
        for i in sorted(range(2), key=lambda i: (-(exact[i] - k[i]), i))[: q - sum(k)]:
            k[i] += 1
        for i, j in ((0, 1), (1, 0)):
            if sizes[i] and not k[i] and k[j] > 1:
                k[i], k[j] = 1, k[j] - 1
        for p, kp in zip(PROGS, k):
            cell = sorted(cells.get((s, p), []),
                          key=lambda r: (r[12], close_key(r[6]), r[1].encode(), int(r[2], 16)))
            n = len(cell)
            out += [cell[(2 * i + 1) * n // (2 * kp)] for i in range(kp)]
    for j, r in enumerate(out):
        r.append("holdout" if j % 2 else "pilot")
    head = [f"# {OUT} -- generated by tools/mmx6/methodsample.py --build; frozen at 3.0 T12, 3.1 reads it as is",
            "# inputs (blob ids): " + " ".join(f"{p}@{b}" for p, b in zip(INPUTS, blobs)),
            "# stratum: refusecause.tsv cause if the row has one, else plateau (plateau:*) or jtbl-uncarved; "
            "other game rows and vendor rows are outside",
            "# quotas: " + " ".join(f"{s} {q}" for s, q in QUOTAS)
            + "; per stratum SLUS/rock by largest remainder (ties SLUS), min 1 per program present",
            "# dup clusters: only the first member by (prog, vram) byte/int order is eligible",
            "# order in a cell: stable sort on (any, closeness m/n as a fraction with nocompile = -1, n, prog bytes, vram); "
            "pick index floor((2i+1)N/(2k)), i = 0..k-1",
            "# file order: quotas order, SLUS then rock, pick order; split: pilot on even row index, holdout on odd (0-based)",
            "# " + "\t".join(COLS.split())]
    return "\n".join(head + ["\t".join(r) for r in out]) + "\n"


def main():
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    if mode == "--build":
        blobs = []
        for p in INPUTS:
            b = git("hash-object", p).strip()
            if b != git("rev-parse", f"HEAD:{p}").strip():
                sys.exit(f"methodsample: {p} differs from HEAD; commit it first")
            blobs.append(b[:12])
        texts = [(ROOT / p).read_text() for p in INPUTS]
        (ROOT / OUT).write_text(build(texts, blobs))
    elif mode == "--check":
        cur = (ROOT / OUT).read_text()
        line = next(l for l in cur.splitlines() if l.startswith("# inputs"))
        blobs = [t.split("@")[1] for t in line.split(": ", 1)[1].split()]
        texts = [git("cat-file", "-p", b) for b in blobs]
        if build(texts, blobs) != cur:
            sys.exit("METHODS-SAMPLE DIFFERS (rebuild from the header's blobs does not match)")
    else:
        sys.exit("usage: methodsample.py --build | --check")
    n = len(rows((ROOT / OUT).read_text()))
    print(f"METHODS-SAMPLE OK {n} rows")


if __name__ == "__main__":
    main()
